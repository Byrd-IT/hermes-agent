"""Kanban linked worktrees provision npm workspace dependencies on first use."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

from hermes_cli import kanban_db_workspace as kbw
from hermes_cli.kanban_db import Task


pytestmark = pytest.mark.skipif(shutil.which("npm") is None, reason="npm is required")


def _run(cwd: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        list(args),
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
        timeout=60,
    )


def _git(cwd: Path, *args: str) -> None:
    _run(cwd, "git", "-c", "user.name=Test User", "-c", "user.email=test@example.com", *args)


def _npm_workspace_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    package_a = repo / "packages" / "a"
    package_b = repo / "packages" / "b"
    package_a.mkdir(parents=True)
    package_b.mkdir()
    (repo / "package.json").write_text(
        '{"name":"fixture-root","private":true,"workspaces":["packages/*"]}\n', encoding="utf-8"
    )
    (package_a / "package.json").write_text(
        '{"name":"@fixture/a","version":"1.0.0"}\n', encoding="utf-8"
    )
    (package_b / "package.json").write_text(
        '{"name":"@fixture/b","version":"1.0.0","dependencies":{"@fixture/a":"*"}}\n',
        encoding="utf-8",
    )
    (package_a / "index.js").write_text("module.exports = 'a';\n", encoding="utf-8")
    (package_b / "index.js").write_text("module.exports = 'b';\n", encoding="utf-8")
    _run(repo, "npm", "install", "--package-lock-only", "--ignore-scripts")
    _run(repo, "git", "init", "-b", "main")
    _git(repo, "add", ".")
    _git(repo, "commit", "-m", "init npm workspace")
    return repo


def test_ensure_git_worktree_installs_npm_workspace_dependencies(tmp_path: Path) -> None:
    repo = _npm_workspace_repo(tmp_path)
    target = repo / ".worktrees" / "t_npmdeps"

    kbw._ensure_git_worktree(repo, target, "wt/t_npmdeps")

    assert (target / "node_modules").is_dir()
    resolved = _run(target, "node", "-p", "require.resolve('@fixture/a')")
    assert Path(resolved.stdout.strip()).is_relative_to(target)


def test_ensure_git_worktree_repairs_existing_npm_workspace_without_dependencies(tmp_path: Path) -> None:
    repo = _npm_workspace_repo(tmp_path)
    target = repo / ".worktrees" / "t_existing_npmdeps"
    target.parent.mkdir()
    _run(repo, "git", "worktree", "add", "-b", "wt/t_existing_npmdeps", str(target), "HEAD")

    kbw._ensure_git_worktree(repo, target, "wt/t_existing_npmdeps")

    resolved = _run(target, "node", "-p", "require.resolve('@fixture/a')")
    assert Path(resolved.stdout.strip()).is_relative_to(target)


def test_resolve_worktree_repairs_existing_same_branch_npm_workspace(tmp_path: Path) -> None:
    repo = _npm_workspace_repo(tmp_path)
    target = repo / ".worktrees" / "t_existing_same_branch_npmdeps"
    target.parent.mkdir()
    _run(repo, "git", "worktree", "add", "-b", "wt/t_existing_same_branch_npmdeps", str(target), "HEAD")
    task = Task(
        id="t_existing_same_branch_npmdeps",
        title="repair existing worktree dependencies",
        body=None,
        assignee=None,
        status="running",
        priority=0,
        created_by=None,
        created_at=0,
        started_at=None,
        completed_at=None,
        workspace_kind="worktree",
        workspace_path=str(target),
        claim_lock=None,
        claim_expires=None,
        tenant=None,
        branch_name="wt/t_existing_same_branch_npmdeps",
    )

    workspace, branch = kbw._resolve_worktree_workspace(task)

    assert workspace == target.resolve()
    assert branch == "wt/t_existing_same_branch_npmdeps"
    resolved = _run(target, "node", "-p", "require.resolve('@fixture/a')")
    assert Path(resolved.stdout.strip()).is_relative_to(target)


def test_npm_workspace_provisioning_bounds_network_concurrency(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    (tmp_path / "package.json").write_text(
        '{"name":"fixture-root","private":true,"workspaces":["packages/*"]}\n', encoding="utf-8"
    )
    (tmp_path / "package-lock.json").write_text('{"lockfileVersion":3}\n', encoding="utf-8")
    calls: list[tuple[list[str], Path]] = []

    monkeypatch.setattr(kbw.shutil, "which", lambda _: "/fake/npm")
    monkeypatch.setattr(
        kbw.subprocess,
        "run",
        lambda args, **kwargs: (
            calls.append((args, kwargs["cwd"])) or subprocess.CompletedProcess(args, 0)
        ),
    )

    kbw._provision_npm_workspace_dependencies(tmp_path)

    assert calls[0][1] == tmp_path
    maxsockets_index = calls[0][0].index("--maxsockets")
    assert int(calls[0][0][maxsockets_index + 1]) <= 3
